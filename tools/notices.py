#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.md by reading license fields, not memory.

  python tools/notices.py

It looks at three things and writes what it finds:
  1. the imports of domingo.py, split into standard library and not,
  2. requirements-dev.txt, with each installed distribution's license metadata,
  3. package.json devDependencies, with each installed package's license field.
Anything it cannot resolve is listed as unresolved rather than guessed.
"""

import ast
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"


def app_imports():
    tree = ast.parse((ROOT / "domingo.py").read_text("utf-8"))
    top = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            top.update(a.name.split(".")[0] for a in n.names)
        elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
            top.add(n.module.split(".")[0])
    std = set(getattr(sys, "stdlib_module_names", set()))
    return sorted(top), sorted(m for m in top if std and m not in std)


def python_licenses(names):
    try:
        from importlib import metadata
    except ImportError:
        return {}, names
    found, missing = {}, []
    for name in names:
        try:
            d = metadata.distribution(name)
            lic = (d.metadata.get("License") or "").strip()
            cls = [v.split("::")[-1].strip() for k, v in d.metadata.get_all("Classifier") or []
                   if k == "License"]
            found[name] = {"version": d.version, "license": lic or "see the project page",
                           "classifiers": cls}
        except Exception:
            missing.append(name)
    return found, missing


def node_licenses(names):
    found, missing = {}, []
    for name in names:
        pkg = ROOT / "node_modules" / name / "package.json"
        if not pkg.is_file():
            missing.append(name)
            continue
        try:
            data = json.loads(pkg.read_text("utf-8"))
        except Exception:
            missing.append(name)
            continue
        found[name] = {"version": data.get("version", "?"), "license": str(data.get("license", "?"))}
    return found, missing


def main():
    all_imports, non_std = app_imports()
    dev_py = []
    req = ROOT / "requirements-dev.txt"
    if req.is_file():
        for line in req.read_text("utf-8").splitlines():
            line = line.split("#")[0].strip()
            if line:
                dev_py.append(line.split("==")[0].split(">=")[0].split("<")[0].strip())
    dev_js = []
    pkg = ROOT / "package.json"
    if pkg.is_file():
        dev_js = sorted(json.loads(pkg.read_text("utf-8")).get("devDependencies", {}))

    py_found, py_missing = python_licenses(dev_py)
    js_found, js_missing = node_licenses(dev_js)

    lines = [
        "# Third-party notices",
        "",
        "Generated by `python tools/notices.py`. Do not edit by hand.",
        "",
        "## Runtime",
        "",
        "`domingo.py` imports %d modules, all of them from the Python standard library:"
        % len(all_imports),
        "",
        "    " + ", ".join(all_imports),
        "",
        "Non-standard imports: **%s**." % ("none" if not non_std else ", ".join(non_std)),
        "There is no bundler, no framework, no font file and no native module in the",
        "app. The interface uses fonts already installed on your system, so nothing is",
        "redistributed with the project.",
        "",
        "## Development only",
        "",
        "These are needed to run the test suites. They are not shipped, imported at",
        "runtime, or included in the container image.",
        "",
    ]
    if py_found:
        lines += ["### Python", "", "| package | version | license |", "| --- | --- | --- |"]
        lines += ["| %s | %s | %s |" % (n, d["version"], d["license"]) for n, d in sorted(py_found.items())]
        lines.append("")
    if js_found:
        lines += ["### Node", "", "| package | version | license |", "| --- | --- | --- |"]
        lines += ["| %s | %s | %s |" % (n, d["version"], d["license"]) for n, d in sorted(js_found.items())]
        lines.append("")
    missing = py_missing + js_missing
    if missing:
        lines += ["### Not installed, so not read", "",
                  "These are declared as dev dependencies but were not installed when this",
                  "file was generated, so their license fields were not read:", ""]
        lines += ["- %s" % m for m in missing]
        lines.append("")
    lines += [
        "## Test fixtures",
        "",
        "`tests/fake_engine.py` is written for this project and contains no third-party",
        "code. The screenshots in `docs/screenshots` were captured from this app with",
        "synthetic conversations, so they include no third-party artwork.",
        "",
        "## Fonts",
        "",
        "The interface names fonts that ship with Windows, macOS and common Linux",
        "distributions (Segoe UI, SF Pro, New York, Palatino, Georgia, Menlo, Consolas,",
        "Cascadia Mono). None of them are copied into this repository, and the app",
        "falls back to the next name in the list when one is missing.",
        "",
    ]
    OUT.write_text("\n".join(lines), "utf-8")
    print("wrote %s (%d lines)" % (OUT.name, len(lines)))


if __name__ == "__main__":
    main()
